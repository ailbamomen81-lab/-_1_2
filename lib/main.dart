class SalesViewModel(app: Application) : AndroidViewModel(app) {
    private val db = AppDatabase.getDatabase(app)
    private val productDao = db.productDao()
    private val saleDao = db.saleDao()

    val products = productDao.getAll()
    val sales = saleDao.getAll()
    val totalRevenue = saleDao.getTotalRevenue()

    fun addProduct(name: String, price: Double, qty: Int) = viewModelScope.launch {
        productDao.insert(Product(name = name, price = price, quantity = qty))
    }

    fun deleteProduct(product: Product) = viewModelScope.launch {
        productDao.delete(product)
    }

    fun makeSale(product: Product, qty: Int) = viewModelScope.launch {
        if (product.quantity >= qty) {
            saleDao.insert(
                Sale(
                    productName = product.name,
                    quantity = qty,
                    totalPrice = product.price * qty
                )
            )
            productDao.reduceStock(product.id, qty)
        }
    }
