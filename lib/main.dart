class MainActivity : AppCompatActivity() {
    private lateinit var binding: ActivityMainBinding
    private val viewModel: SalesViewModel by viewModels()
    private lateinit var adapter: ProductAdapter

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        binding = ActivityMainBinding.inflate(layoutInflater)
        setContentView(binding.root)

        adapter = ProductAdapter(
            onSell = { product -> showSellDialog(product) },
            onDelete = { product -> viewModel.deleteProduct(product) }
        )
        binding.rvProducts.layoutManager = LinearLayoutManager(this)
        binding.rvProducts.adapter = adapter

        binding.btnAdd.setOnClickListener {
            val name = binding.etName.text.toString().trim()
            val price = binding.etPrice.text.toString().toDoubleOrNull() ?: 0.0
            val qty = binding.etQty.text.toString().toIntOrNull() ?: 0

            if (name.isEmpty() || price <= 0 || qty <= 0) {
                Toast.makeText(this, "أدخل بيانات صحيحة", Toast.LENGTH_SHORT).show()
                return@setOnClickListener
            }

            viewModel.addProduct(name, price, qty)
            binding.etName.text.clear()
            binding.etPrice.text.clear()
            binding.etQty.text.clear()
            Toast.makeText(this, "تمت الإضافة", Toast.LENGTH_SHORT).show()
        }

        viewModel.products.observe(this) { adapter.submitList(it) }
        viewModel.totalRevenue.observe(this) {
            binding.tvRevenue.text = "إجمالي المبيعات: ${it ?: 0.0}"
        }
    }

    private fun showSellDialog(product: Product) {
        val input = android.widget.EditText(this).apply {
            hint = "الكمية"
            inputType = android.text.InputType.TYPE_CLASS_NUMBER
        }
        AlertDialog.Builder(this)
            .setTitle("بيع: ${product.name}")
            .setMessage("المتاح: ${product.quantity}")
            .setView(input)
            .setPositiveButton("تأكيد") { _, _ ->
                val qty = input.text.toString().toIntOrNull() ?: 0
                if (qty in 1..product.quantity) {
                    viewModel.makeSale(product, qty)
                    Toast.makeText(this, "تم البيع", Toast.LENGTH_SHORT).show()
                } else {
                    Toast.makeText(this, "كمية غير صحيحة", Toast.LENGTH_SHORT).show()
                }
            }
            .setNegativeButton("إلغاء", null)
            .show()
    }
}
